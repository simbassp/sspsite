-- Announcement: achievements system guide (author: Денис Симба)
do $$
declare
  author_user_id uuid;
  author_position text;
  news_body text;
begin
  select id, position
  into author_user_id, author_position
  from public.app_users
  where lower(trim(name)) = 'денис'
    and lower(trim(callsign)) in ('симба', 'simba', 'сimba')
  order by created_at asc nulls last
  limit 1;

  news_body := $body$
Коллеги, на платформе заработала система достижений. Кратко — как это устроено.

[b]Общие правила[/b]
Достижения открываются автоматически, когда выполнены условия. О новой награде приходит уведомление на сайте.
В профиле нажмите ⭐ — там можно выбрать рамку аватара и цвет позывного из уже полученных уровней.

В зачёт идут только сданные тесты (статус «пройден»). Неудачные попытки не считаются.

[b]Стаж — медали в профиле[/b]
Считается с даты трудоустройства:
1 месяц — деревянная медаль,
6 месяцев — каменная,
1 год — бронзовая,
2 года — серебряная,
3 года — золотая,
4 года — платиновая,
5 лет — алмазная.
Медали отображаются в профиле в блоке достижений.

[b]Пробные тесты — рамки аватара[/b]
За количество сданных пробных тестов: 100, 250, 500, 1000, 5000 и 10000.
Чем выше уровень — тем заметнее рамка вокруг аватара.
Выбрать можно любую из уже открытых — в профиле через ⭐.

[b]Итоговые тесты — цвет позывного[/b]
За количество сданных итоговых тестов: 50, 100, 250, 500, 1000 и 5000.
Открывает цвет имени и позывного. Выбор — в профиле через ⭐.

[b]Топ сотрудников — значок на аватаре[/b]
Три лучших по активности в разделе «Сотрудники» (4-я рота) получают значки 1, 2 и 3 на аватаре.
Это не постоянная медаль в профиле — пересчитывается по текущему рейтингу.

[b]Важно[/b]
Если администратор назначил вам персональный цвет имени — он имеет приоритет над цветом от достижений.

Вопросы — в чат или администратору.
$body$;

  if not exists (
    select 1
    from public.news
    where title = 'Система достижений на платформе'
  ) then
    insert into public.news (
      title,
      body,
      priority,
      author,
      author_id,
      created_by,
      author_position,
      format
    )
    values (
      'Система достижений на платформе',
      trim(both E'\n' from news_body),
      'high',
      'Денис Симба',
      author_user_id,
      author_user_id,
      author_position,
      jsonb_build_object(
        'fontSize', 16,
        'bold', false,
        'italic', false,
        'underline', false,
        'kind', 'update'
      )
    );
  end if;
end $$;
